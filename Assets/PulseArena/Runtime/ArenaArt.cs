using System.Collections.Generic;
using UnityEngine;
using UnityEngine.SceneManagement;

namespace PulseArena
{
    public static class ArenaArt
    {
        public static readonly Color Cyan = new Color(.16f, .92f, 1f);
        public static readonly Color Amber = new Color(1f, .51f, .17f);
        static readonly Dictionary<string, Material> materials = new Dictionary<string, Material>();
        static readonly Dictionary<string, GameObject> prefabs = new Dictionary<string, GameObject>();
        static readonly int BaseColorId = Shader.PropertyToID("_BaseColor");
        static readonly int ColorId = Shader.PropertyToID("_Color");

        public static Material Mat(string name)
        {
            if (!materials.TryGetValue(name, out var m) || !m)
                materials[name] = m = Resources.Load<Material>("Materials/" + name);
            return m;
        }

        /// Loads a prefab generated by PulseWorldBuilder from Resources/World.
        public static GameObject WorldPrefab(string name)
        {
            if (!prefabs.TryGetValue(name, out var p) || !p)
                prefabs[name] = p = Resources.Load<GameObject>("World/" + name);
            return p;
        }

        // Destroy is illegal in edit mode (the editor generation step builds the arena there).
        internal static void Kill(Object o)
        {
            if (!o) return;
            if (Application.isPlaying) Object.Destroy(o); else Object.DestroyImmediate(o);
        }

        public static GameObject Shape(string name, PrimitiveType type, Transform parent, Vector3 pos, Vector3 size, string material, bool solid = false)
        {
            var go = GameObject.CreatePrimitive(type); go.name = name;
            go.transform.SetParent(parent, false); go.transform.localPosition = pos; go.transform.localScale = size;
            go.GetComponent<Renderer>().sharedMaterial = Mat(material);
            if (!solid) { var c = go.GetComponent<Collider>(); if (c) { c.enabled = false; Kill(c); } }
            return go;
        }
        static GameObject Box(string name, Transform parent, Vector3 pos, Vector3 size, string mat, bool solid = true)
            => Shape(name, PrimitiveType.Cube, parent, pos, size, mat, solid);

        // ---------------------------------------------------------------- arena

        /// Uses the arena baked into the scene when there is one (and discards the empty root
        /// the caller made); otherwise builds the same layout at runtime from the Resources prefabs.
        public static void BuildArena(Transform root)
        {
            foreach (var go in SceneManager.GetActiveScene().GetRootGameObjects())
            {
                if (go && go.name == ArenaLayout.RootName && go != root.gameObject)
                {
                    Object.DestroyImmediate(root.gameObject);
                    return;
                }
            }
            if (!WorldPrefab("Arena_floor")) BuildBasicFallback(root);
            ArenaLayout.Build(root, (piece, parent) =>
            {
                var prefab = WorldPrefab("Arena_" + piece);
                return prefab ? Object.Instantiate(prefab, parent, false) : null;
            });
        }

        // Only used if the generated prefabs are missing, so the pilot is never left in a void.
        static void BuildBasicFallback(Transform root)
        {
            Box("Foundation", root, new Vector3(0, -.4f, 0), new Vector3(48, .8f, 48), "Floor");
            for (int side = 0; side < 4; side++)
            {
                var wall = new GameObject("Perimeter " + side).transform; wall.SetParent(root, false); wall.localRotation = Quaternion.Euler(0, side * 90, 0);
                Box("Wall", wall, new Vector3(0, 2.2f, 24), new Vector3(49, 4.4f, 1), "Wall");
            }
        }

        public static Vector3 Spawn(int index) => ArenaLayout.Spawn(index);
        public static Quaternion SpawnRotation(int index) => ArenaLayout.SpawnRotation(index);
        public static Vector3[] PickupSpots(PickupKind kind) => ArenaLayout.PickupSpots(kind);

        // ---------------------------------------------------------------- pilots

        static readonly Color[] humanAccents = { new Color(.35f, .95f, 1f), new Color(.6f, 1f, .45f), new Color(.85f, .62f, 1f), new Color(1f, .6f, .82f) };
        static readonly Color[] botAccents = { new Color(1f, .5f, .15f), new Color(1f, .3f, .3f), new Color(1f, .8f, .2f) };

        static Transform FindDeep(Transform t, string name)
        {
            if (t.name == name) return t;
            for (int i = 0; i < t.childCount; i++) { var f = FindDeep(t.GetChild(i), name); if (f) return f; }
            return null;
        }

        /// Creates the pilot character under root and returns its root. Bots (glow "Amber") use PilotBot.
        public static Transform Robot(Transform root, string glow)
        {
            bool bot = glow == "Amber";
            var prefab = WorldPrefab(bot ? "PilotBot" : "PilotHuman");
            if (!prefab) return RobotFallback(root, glow);

            var model = Object.Instantiate(prefab, root, false).transform;
            model.name = "Pilot model";
            model.localPosition = Vector3.zero; model.localRotation = Quaternion.identity;

            var pilot = root.GetComponent<ArenaPlayer>();

            // Per-pilot accent through a property block: no material instances.
            Color accent = bot ? botAccents[(pilot ? (int)(pilot.NetworkObjectId % 3) : 0)] : humanAccents[(pilot ? (int)(pilot.OwnerClientId % 4) : 0)];
            var block = new MaterialPropertyBlock();
            Color tint = Color.Lerp(Color.white, accent, .7f);
            block.SetColor(BaseColorId, tint); block.SetColor(ColorId, tint);
            foreach (var r in model.GetComponentsInChildren<SkinnedMeshRenderer>(true)) r.SetPropertyBlock(block);

            var hand = FindDeep(model, "HandAttach");
            if (hand) WeaponThirdPerson(hand, WeaponId.Carbine);

            var animator = model.GetComponentInChildren<Animator>(true);
            if (animator)
            {
                animator.cullingMode = AnimatorCullingMode.CullUpdateTransforms;
                animator.applyRootMotion = false;
            }
            var driver = root.GetComponent<PilotAnimator>();
            if (!driver) driver = root.gameObject.AddComponent<PilotAnimator>();
            driver.Init(pilot, animator);
            return model;
        }

        static Transform RobotFallback(Transform root, string glow)
        {
            var model = new GameObject("Sentinel chassis").transform; model.SetParent(root, false);
            Shape("Torso", PrimitiveType.Capsule, model, new Vector3(0, 1.13f, 0), new Vector3(.64f, .38f, .44f), "Steel");
            Box("Chest armor", model, new Vector3(0, 1.24f, .22f), new Vector3(.62f, .4f, .18f), "Armor", false);
            Box("Chest reactor", model, new Vector3(0, 1.25f, .32f), new Vector3(.12f, .24f, .03f), glow, false);
            Shape("Head", PrimitiveType.Sphere, model, new Vector3(0, 1.75f, 0), new Vector3(.47f, .44f, .43f), "Armor");
            Box("Visor", model, new Vector3(0, 1.78f, .21f), new Vector3(.4f, .11f, .08f), glow, false);
            for (int side = -1; side <= 1; side += 2)
            {
                Box(side < 0 ? "LeftLeg" : "RightLeg", model, new Vector3(side * .21f, .51f, 0), new Vector3(.25f, .85f, .28f), "Armor", false);
                Box("Shoulder", model, new Vector3(side * .47f, 1.45f, 0), new Vector3(.29f, .28f, .36f), "Armor", false);
                var arm = Box("Arm", model, new Vector3(side * .43f, 1.13f, .15f), new Vector3(.2f, .54f, .22f), "Steel", false); arm.transform.localRotation = Quaternion.Euler(-30, 0, 0);
            }
            var gun = Weapon(model); gun.localPosition = new Vector3(.32f, 1.13f, .42f); gun.localScale = Vector3.one * .65f;
            return model;
        }

        // ---------------------------------------------------------------- weapons

        /// First-person scale weapon (about 0.6 m long, origin near the grip, barrel along +Z).
        /// The returned root contains a child named "Muzzle" at the barrel tip.
        public static Transform Weapon(Transform parent, WeaponId id)
        {
            var prefab = WorldPrefab(id == WeaponId.Scatter ? "Weapon_Scatter" : "Weapon_Carbine");
            if (!prefab) return WeaponFallback(parent);
            var root = Object.Instantiate(prefab, parent, false).transform;
            root.name = id == WeaponId.Scatter ? "SX-8 Scatter Cannon" : "PX-24 Pulse Carbine";
            root.localPosition = Vector3.zero; root.localRotation = Quaternion.identity; root.localScale = Vector3.one;
            return root;
        }
        public static Transform Weapon(Transform parent) => Weapon(parent, WeaponId.Carbine);

        /// Weapon held in a character's hand. Compensates the rig's scale so the gun is about 0.7 m long.
        public static Transform WeaponThirdPerson(Transform hand, WeaponId id)
        {
            var gun = Weapon(hand, id);
            float s = Mathf.Max(.0001f, hand.lossyScale.x);
            gun.localScale = Vector3.one * (1.15f / s);
            return gun;
        }

        static Transform WeaponFallback(Transform parent)
        {
            var root = new GameObject("PX-24 Pulse Carbine").transform; root.SetParent(parent, false);
            Box("Receiver", root, Vector3.zero, new Vector3(.19f, .2f, .62f), "Armor", false);
            Box("Stock", root, new Vector3(0, -.04f, -.39f), new Vector3(.14f, .24f, .24f), "Steel", false);
            var barrel = Shape("Barrel", PrimitiveType.Cylinder, root, new Vector3(0, .015f, .44f), new Vector3(.105f, .16f, .105f), "Steel"); barrel.transform.localRotation = Quaternion.Euler(90, 0, 0);
            var muzzle = new GameObject("Muzzle").transform; muzzle.SetParent(root, false); muzzle.localPosition = new Vector3(0, .015f, .62f);
            root.localScale = Vector3.one * .6f;
            return root;
        }
    }
}
